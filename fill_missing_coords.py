def main():
    con = sqlite3.connect(DB)
    cur = con.cursor()
    missing = cur.execute(
        "SELECT id, name FROM stations WHERE lng IS NULL OR lat IS NULL").fetchall()
    print(f"缺坐标车站: {len(missing)}")
    done, failed = 0, []
    for sid, name in missing:
        c = COORDS.get(name)
        if c is None:
            failed.append(name)
            continue
        cur.execute("UPDATE stations SET lng=?, lat=? WHERE id=?", (c[0], c[1], sid))
        done += 1
    con.commit()
    left = cur.execute(
        "SELECT COUNT(*) FROM stations WHERE lng IS NULL OR lat IS NULL").fetchone()[0]
    print(f"已补 {done} 个, 仍未覆盖 {left} 个")
    if failed:
        print("脚本表未收录(需人工补充):", failed)
    # 顺带把 WAL 落盘, 避免 PyInstaller 打包漏数据
    cur.execute("PRAGMA wal_checkpoint(TRUNCATE)")
    con.close()
    return 1 if (failed or left) else 0


if __name__ == "__main__":
    sys.exit(main())
